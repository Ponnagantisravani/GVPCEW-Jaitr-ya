const fs=require('node:fs');const vm=require('node:vm');const assert=require('node:assert/strict');
const html=fs.readFileSync('public/academic-calendar.html','utf8');
const script=html.match(/<script>([\s\S]*?)<\/script>/)[1];new vm.Script(script);
const lines=script.split('\n');
const selected=lines.filter(l=>/^(const PUBLIC_HOLIDAYS=|const AP_GENERAL_HOLIDAYS_2026=|PUBLIC_HOLIDAYS.splice)/.test(l)).join('\n');
const fn=script.slice(script.indexOf('function holidayDays('),script.indexOf('function render()'));
const ctx={calendar:{year:'2026–27',holidays:[{name:'Dussehra break',from:'18-10-2026',to:'24-10-2026'}]},parseDate:s=>Date.parse(s+'T00:00:00Z')/86400000,display:d=>new Date(d*86400000).toISOString().slice(0,10).split('-').reverse().join('-'),parseDisplay:s=>Date.parse(s.split('-').reverse().join('-')+'T00:00:00Z')/86400000};vm.createContext(ctx);vm.runInContext(selected+'\n'+fn+'\nthis.result=sortedHolidays();',ctx);
assert.equal(ctx.result.filter(h=>h.from.endsWith('2026')&&h.soft).length,24);
assert(ctx.result.some(h=>h.name==='Vijaya Dasami'&&h.from==='20-10-2026'));
assert(ctx.result.some(h=>h.name==='Dussehra break'));
assert(ctx.result.some(h=>h.name==='Ugadi'&&h.from==='19-03-2026'));
assert(ctx.result.some(h=>h.name==='Eid-ul-Fitr (Ramzan)'&&h.from==='20-03-2026'));
ctx.calendar.holidays=ctx.result;vm.runInContext('this.result=sortedHolidays()',ctx);
assert.equal(ctx.result.filter(h=>h.from.endsWith('2026')&&h.soft).length,24);
assert.equal(vm.runInContext("holidayDays({from:'18-10-2026',to:'24-10-2026'})",ctx),7);
assert.equal(vm.runInContext("holidayDays({from:'14-01-2026',to:''})",ctx),1);
assert.equal(vm.runInContext("holidayDays({from:'30-12-2026',to:'02-01-2027'})",ctx),4);
assert(html.includes('<th>NUMBER OF DAYS</th>'));
assert(html.includes("holidayDays(h)>1?' class=\"holiday-multiple-days\"':''"));
console.log('Calendar checks passed: public holidays, major breaks, inclusive day counts, and multi-day highlighting.');
